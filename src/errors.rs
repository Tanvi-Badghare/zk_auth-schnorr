/// Centralised error and Result types for zk-auth.
///
/// Every public function in the library returns [`Result<T>`], which is an alias
/// for `std::result::Result<T, ZkAuthError>`.  Downstream code can match on
/// the enum variants or call `.kind()` / standard trait methods.
use thiserror::Error;

// ---------------------------------------------------------------------------
// Result alias
// ---------------------------------------------------------------------------

/// Library-wide Result type.  `T` is the success value; the error is always
/// [`ZkAuthError`].
pub type Result<T> = std::result::Result<T, ZkAuthError>;

// ---------------------------------------------------------------------------
// Error enum
// ---------------------------------------------------------------------------

/// Every failure mode that can occur inside zk-auth.
///
/// Variants are grouped by the layer that produces them.  The [`std::fmt::Display`]
/// impl (generated by `thiserror`) is kept human-readable for logging.
#[derive(Error, Debug, Clone)]
pub enum ZkAuthError {
    // =====================================================================
    // Crypto-layer errors
    // =====================================================================

    /// A scalar value is outside the valid field range [1, order-1].
    #[error("Invalid scalar value")]
    InvalidScalar,

    /// A point is not on the expected curve, or is the point at infinity
    /// when a non-identity point was required.
    #[error("Invalid elliptic curve point")]
    InvalidPoint,

    /// An internal hashing operation failed (e.g. digest finalisation).
    #[error("Hashing failure")]
    HashError,

    /// The operating system (or the configured RNG crate) could not produce
    /// the requested number of random bytes.
    #[error("Randomness generation failure")]
    RngFailure,

    // =====================================================================
    // Protocol-layer errors  (proof structure & verification)
    // =====================================================================

    /// The proof object is structurally malformed (wrong size, missing
    /// fields, etc.).
    #[error("Invalid proof")]
    InvalidProof,

    /// The proof is well-formed but the verification equation does not hold.
    #[error("Verification failed")]
    VerificationFailed,

    /// The Fiat–Shamir challenge embedded in a proof does not match the
    /// value recomputed from the transcript.
    #[error("Challenge mismatch")]
    ChallengeMismatch,

    /// The protocol transcript is in an inconsistent or incomplete state
    /// (e.g. messages arrived out of order).
    #[error("Transcript error")]
    TranscriptError,

    // =====================================================================
    // Registration / Authentication errors
    // =====================================================================

    /// An attempt was made to register an identifier that already exists in
    /// the credential store.
    #[error("User already registered: {0}")]
    UserAlreadyExists(String),

    /// A lookup for the given identifier returned no results.
    #[error("User not found: {0}")]
    UserNotFound(String),

    /// The authentication attempt did not succeed (credentials did not
    /// match).  Deliberately vague to avoid leaking which step failed.
    #[error("Authentication failed")]
    AuthenticationFailed,

    // =====================================================================
    // Serialization errors
    // =====================================================================

    /// A value could not be serialised to its wire format.
    /// The inner string describes *what* failed (e.g. "proof → bytes").
    #[error("Serialization failure: {0}")]
    SerializationError(String),

    /// Bytes could not be deserialised into the expected type.
    /// The inner string describes *what* failed (e.g. "bytes → keypair").
    #[error("Deserialization failure: {0}")]
    DeserializationError(String),

    // =====================================================================
    // Configuration errors
    // =====================================================================

    /// A configuration value is missing, out of range, or otherwise invalid.
    /// The inner string names the offending key or constraint.
    #[error("Invalid configuration: {0}")]
    InvalidConfig(String),

    // =====================================================================
    // Catch-all
    // =====================================================================

    /// An unexpected internal error that does not fit the categories above.
    /// Use sparingly — prefer a specific variant when possible.
    #[error("Internal error: {0}")]
    Internal(String),
}